// Fail if the committed API client no longer matches the backend's OpenAPI document.
//
// packages/api-core/src/generated is generated from backend-go/openapi/core.json
// and committed, which buys two things: a checkout builds and typechecks with no
// backend and no network, and a backend change shows up as a reviewable diff in
// the frontend rather than as a runtime surprise. Both depend on the committed
// copy actually being current, and nothing else notices when it is not -- the
// stale client compiles perfectly, it just describes an API that has moved.
//
// So this regenerates into a scratch directory and compares. Comparing rather
// than regenerating in place is deliberate: a check that rewrites the tree it is
// checking turns a red CI run into a dirty working copy, and locally it would
// quietly "fix" the drift instead of reporting it.
//
// Usage: node scripts/api-drift-check.mjs

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const PACKAGE = path.join(ROOT, 'packages', 'api-core')
const COMMITTED = path.join(PACKAGE, 'src', 'generated')
const SPEC = path.resolve(ROOT, '..', 'backend-go', 'openapi', 'core.json')
const CLI = path.join(PACKAGE, 'node_modules', '@hey-api', 'openapi-ts', 'bin', 'run.js')
const REGENERATE = 'pnpm --filter @gamemap/api-core generate'
// Read by openapi-ts.config.ts to redirect the output. Set only by this script.
const OUT_VAR = 'ARKIVE_API_CORE_OUT'

/** Every generated file, as a path-keyed map, so a missing file is a difference too. */
function snapshot(dir, base = dir, out = new Map()) {
  if (!fs.existsSync(dir)) return out
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) snapshot(full, base, out)
    // Normalised to forward slashes and LF so the comparison does not depend on
    // which platform generated the committed copy. Windows checks out CRLF for
    // some files, and a line-ending difference is not drift.
    else out.set(path.relative(base, full).split(path.sep).join('/'), fs.readFileSync(full, 'utf8').replace(/\r\n/g, '\n'))
  }
  return out
}

function fail(message) {
  console.error(`api-drift: ${message}`)
  process.exit(1)
}

if (!fs.existsSync(SPEC)) {
  // Not a silent pass. The spec lives in this repository, so an absent file means
  // a move or a bad checkout, and treating that as "nothing to check" would
  // disable the gate exactly when it stopped working.
  fail(`cannot find ${path.relative(ROOT, SPEC)}. The OpenAPI document is generated by: cd backend-go && go run ./cmd/arkive openapi`)
}

if (!fs.existsSync(CLI)) {
  fail(`cannot find the generator at ${path.relative(ROOT, CLI)}. Run: pnpm install`)
}

if (process.env[OUT_VAR]) {
  // Already exported in this shell, which would send BOTH the committed
  // regeneration and this check's scratch run into that directory -- and the
  // generator's `clean` default empties its output first. Refusing is the only
  // safe reading: the variable exists for this script to set, so finding it set
  // means something else is driving the output.
  fail(`${OUT_VAR} is already set (${process.env[OUT_VAR]}). Unset it: it is this script's to set.`)
}

const before = snapshot(COMMITTED)
if (before.size === 0) fail(`${path.relative(ROOT, COMMITTED)} is empty or missing. Run: ${REGENERATE}`)

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'arkive-api-drift-'))
try {
  // The generator's own JS entry point under this Node, rather than `pnpm exec`.
  // Two Windows problems disappear: Node refuses to spawnSync a `.cmd` without a
  // shell, and spawning through a shell concatenates rather than escapes the
  // arguments -- one of which is a temp path.
  //
  // Redirected with an environment variable that openapi-ts.config.ts reads, NOT
  // with the CLI's `--output` flag. That flag replaces the entire `output` object
  // instead of merging into it, so the scratch run would take the default for
  // every other output option while the committed copy was generated with the
  // configured ones -- and this check would then report drift forever, in files
  // nobody had touched. One config object, one set of options, both runs.
  execFileSync(process.execPath, [CLI], {
    cwd: PACKAGE,
    stdio: 'pipe',
    env: { ...process.env, [OUT_VAR]: scratch },
  })

  // The committed tree must be exactly as it was found. This script's header
  // promises it compares rather than rewrites -- a check that "fixes" drift
  // reports nothing and leaves a dirty working copy -- and if the config ever
  // stopped reading OUT_VAR, the regeneration above would land here instead, with
  // `clean` emptying it first. Cheaper to prove than to trust.
  const afterCommitted = snapshot(COMMITTED)
  const touched = [...new Set([...before.keys(), ...afterCommitted.keys()])]
    .filter((name) => before.get(name) !== afterCommitted.get(name))
    .sort()
  if (touched.length > 0) {
    fail(`the committed tree was modified by this check, which it must never do: ${touched.join(', ')}. Restore it with git, then check that openapi-ts.config.ts still reads ${OUT_VAR}.`)
  }

  const after = snapshot(scratch)
  if (after.size === 0) fail(`regeneration produced nothing. Check openapi-ts.config.ts, then run: ${REGENERATE}`)

  const names = [...new Set([...before.keys(), ...after.keys()])].sort()
  const drifted = names.filter((name) => before.get(name) !== after.get(name))

  if (drifted.length > 0) {
    console.error(`api-drift: the committed client is stale. Run: ${REGENERATE}`)
    for (const name of drifted) {
      const state = !before.has(name) ? 'missing from the commit' : !after.has(name) ? 'no longer generated' : 'differs'
      console.error(`  ${name} -- ${state}`)
    }
    process.exit(1)
  }

  console.log(`api-drift: ${before.size} generated files match ${path.relative(ROOT, SPEC)}`)
} finally {
  fs.rmSync(scratch, { recursive: true, force: true })
}
