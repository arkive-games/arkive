#!/usr/bin/env node
import { createHash, randomUUID } from 'node:crypto'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const FRONTEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const META_REQUIRE = createRequire(path.join(FRONTEND, 'apps/meta/package.json'))
// The version directory is a CONTENT HASH, not a hand-incremented number.
//
// Everything under it is served `immutable` for a year, so a subset whose bytes
// change while its URL stays the same is cached wrong for that year -- and the
// woff2 filenames are stable (`noto-sans-sc-4-wght-normal.woff2`), so a font
// package bump changes contents without changing any filename. A hand-written
// `v1` made not-bumping-it the silent default; a hash makes the URL move
// whenever any served byte moves, and stay put when nothing does.
const FONT_FAMILY_ROOT = path.join(FRONTEND, 'apps/meta/public/fonts/noto-sans')
const MANIFEST = path.join(FONT_FAMILY_ROOT, 'manifest.json')
const STAGING = path.join(FONT_FAMILY_ROOT, `.staging-${randomUUID()}`)
const PACKAGES = [
  '@fontsource-variable/noto-sans-sc',
  '@fontsource-variable/noto-sans-tc',
]

const packageRoots = PACKAGES.map((name) => path.dirname(META_REQUIRE.resolve(`${name}/package.json`)))
const licenses = packageRoots.map((root) => fs.readFileSync(path.join(root, 'LICENSE'), 'utf8'))
if (!licenses.every((license) => license === licenses[0])) {
  throw new Error('Font packages no longer share the same license')
}

// Build into staging first: the hash cannot be known until every byte is written,
// and a half-written version directory must never be left behind under a name that
// the plugin would then resolve and publish.
fs.rmSync(STAGING, { recursive: true, force: true })
fs.mkdirSync(path.join(STAGING, 'files'), { recursive: true })

const css = packageRoots
  .map((root) => fs.readFileSync(path.join(root, 'index.css'), 'utf8').trim())
  .join('\n\n')
fs.writeFileSync(
  path.join(STAGING, 'index.css'),
  `/* Generated by pnpm fonts:sync. Do not edit directly. */\n${css}\n`,
)
fs.writeFileSync(path.join(STAGING, 'LICENSE.txt'), licenses[0])

let fileCount = 0
for (const root of packageRoots) {
  for (const entry of fs.readdirSync(path.join(root, 'files'), { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.woff2')) continue
    fs.copyFileSync(
      path.join(root, 'files', entry.name),
      path.join(STAGING, 'files', entry.name),
    )
    fileCount += 1
  }
}

/** Every file under `dir`, as repository-style relative paths, sorted. */
function listFiles(dir, prefix = '') {
  return fs.readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory()
      ? listFiles(path.join(dir, entry.name), `${prefix}${entry.name}/`)
      : [`${prefix}${entry.name}`]))
    .sort()
}

// Hash names AND bytes: renaming a subset changes what the CSS resolves to even
// when the bytes are untouched. Sorted, and with the path length framed in, so the
// digest cannot depend on readdir order or on where one name ends and the next
// begins.
const digest = createHash('sha256')
for (const relative of listFiles(STAGING)) {
  digest.update(`${relative.length}:${relative}`)
  digest.update(fs.readFileSync(path.join(STAGING, relative)))
}
const version = digest.digest('hex').slice(0, 16)
const output = path.join(FONT_FAMILY_ROOT, version)

// Exactly one version directory may exist, so that resolution is never ambiguous
// and stale subsets cannot be served by a leftover path. Old URLs stay valid in
// caches that already hold them; they simply stop being published.
// Computed before the rename, so the staging directory has to be excluded explicitly
// -- it is about to BECOME the version directory, not a leftover to delete.
const stale = fs.readdirSync(FONT_FAMILY_ROOT, { withFileTypes: true })
  .filter((entry) => entry.isDirectory()
    && entry.name !== version
    && path.join(FONT_FAMILY_ROOT, entry.name) !== STAGING)
  .map((entry) => entry.name)

if (fs.existsSync(output)) {
  fs.rmSync(STAGING, { recursive: true, force: true })
} else {
  fs.renameSync(STAGING, output)
}
for (const name of stale) fs.rmSync(path.join(FONT_FAMILY_ROOT, name), { recursive: true, force: true })

fs.writeFileSync(MANIFEST, `${JSON.stringify({ version, fileCount }, null, 2)}\n`)

const verb = stale.length === 0 ? 'unchanged at' : `moved from ${stale.join(', ')} to`
console.log(`fonts:sync: ${fileCount} WOFF2 files, ${verb} ${version}`)
